def prose(x):
    """what a record says in words: its title, `stated_as` and every other field of text it holds, nested ones too,
    never its ids and references, so that a question meets what the record is about"""
    out = []
    def walk(v, key=None):
        if key in NOT_PROSE:
            return
        if isinstance(v, str):
            if " " in v.strip() or key in ("title", "stated_as", "name"):
                out.append(v)
        elif isinstance(v, dict):
            for k2, v2 in v.items():
                walk(v2, k2)
        elif isinstance(v, list):
            for v2 in v:
                walk(v2, key)
    walk(x)
    return out


